CREATE DATABASE IF NOT EXISTS wattie CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE wattie;

CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 email VARCHAR(120) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 bio VARCHAR(500) DEFAULT '',
 avatar_url VARCHAR(500) DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS stories (
 id INT AUTO_INCREMENT PRIMARY KEY,
 user_id INT NOT NULL,
 title VARCHAR(180) NOT NULL,
 description TEXT,
 cover_url VARCHAR(1000) DEFAULT NULL,
 genre VARCHAR(60) DEFAULT 'Romance',
 status ENUM('draft','published') DEFAULT 'draft',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX idx_story_status (status), INDEX idx_story_title (title)
);
CREATE TABLE IF NOT EXISTS chapters (
 id INT AUTO_INCREMENT PRIMARY KEY,
 story_id INT NOT NULL,
 chapter_number INT NOT NULL,
 title VARCHAR(180) NOT NULL,
 content LONGTEXT NOT NULL,
 published_at TIMESTAMP NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY unique_chapter (story_id, chapter_number),
 FOREIGN KEY (story_id) REFERENCES stories(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS favorites (
 user_id INT NOT NULL,
 story_id INT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (user_id, story_id),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (story_id) REFERENCES stories(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS comments (
 id INT AUTO_INCREMENT PRIMARY KEY,
 user_id INT NOT NULL,
 story_id INT NOT NULL,
 body VARCHAR(1500) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (story_id) REFERENCES stories(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS follows (
 follower_id INT NOT NULL,
 followed_id INT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (follower_id, followed_id),
 FOREIGN KEY (follower_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (followed_id) REFERENCES users(id) ON DELETE CASCADE
);
